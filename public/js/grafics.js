// Это подписи для горизонтальной оси графика.
// Они будут отображаться внизу графика.
const months = [
  "Янв",  // январь
  "Фев",  // февраль
  "Мар",  // март
  "Апр",  // апрель
  "Май",  // май
  "Июн",  // июнь
  "Июл",  // июль
  "Авг",  // август
  "Сен",  // сентябрь
  "Окт",  // октябрь
  "Ноя",  // ноябрь
  "Дек",  // декабрь
];


// ===============================
// 🔹 ДАННЫЕ ПРОДАЖ ПО ТОВАРАМ
// ===============================

// Объект, где:
// ключ — название товара
// значение — массив продаж по месяцам
// (порядок чисел соответствует массиву months)
const salesData = {

  // Продажи товара "Стул Classic" за 12 месяцев
  "Стул Classic": [
    1200, 1500, 1300, 1800, 2000, 2200,
    1900, 2100, 2300, 2500, 2700, 3000,
  ],

  // Продажи товара "Стол Loft"
  "Стол Loft": [
    800, 900, 1100, 1200, 1500, 1600,
    1700, 1800, 1900, 2000, 2100, 2200,
  ],

  // Продажи товара "Диван Relax"
  "Диван Relax": [
    2000, 2100, 2200, 2300, 2400, 2500,
    2600, 2700, 2800, 2900, 3000, 3100,
  ],
};


// ===============================
// 🔹 ЦВЕТА ДЛЯ ЛИНИЙ ГРАФИКА
// ===============================

// Цвет линии (границы)
const colors = [
  "rgba(78, 115, 223, 1)",   // синий
  "rgba(28, 200, 138, 1)",   // зелёный
  "rgba(246, 194, 62, 1)",   // жёлтый
];

// Цвет заливки под линией (полупрозрачный)
const bgColors = [
  "rgba(78, 115, 223, 0.2)",
  "rgba(28, 200, 138, 0.2)",
  "rgba(246, 194, 62, 0.2)",
];


// ===============================
// 🔹 СОЗДАНИЕ DATASETS ДЛЯ CHART.JS
// ===============================

// Object.keys(salesData) — получаем массив названий товаров
// map() — создаём массив объектов для Chart.js
const datasets = Object.keys(salesData).map((key, i) => ({

  // Название линии в легенде
  label: key,

  // Данные продаж
  data: salesData[key],

  // Цвет линии (берём по индексу)
  borderColor: colors[i % colors.length],

  // Цвет заливки под линией
  backgroundColor: bgColors[i % bgColors.length],

  // Насколько сглажена линия (0 — острые углы, 1 — сильное сглаживание)
  tension: 0.3,

  // Включаем заливку под линией
  fill: true,

  // Радиус точек на графике
  pointRadius: 4,

  // Радиус точки при наведении мыши
  pointHoverRadius: 6,
}));


// ===============================
// 🔹 ПОЛУЧАЕМ CANVAS
// ===============================

// Получаем элемент <canvas id="salesChart">
// getContext("2d") — контекст для 2D-графики
const ctx = document
  .getElementById("salesChart")
  .getContext("2d");


// ===============================
// 🔹 СОЗДАНИЕ ГРАФИКА
// ===============================

const salesChart = new Chart(ctx, {

  // Тип графика — линейный
  type: "line",

  // Основные данные
  data: {
    labels: months,     // подписи по оси X
    datasets: datasets, // линии графика
  },

  // Настройки графика
  options: {

    // Адаптивность (подстраивается под экран)
    responsive: true,

    plugins: {

      // Настройка легенды (список товаров сверху)
      legend: {
        display: true,   // показывать легенду
        position: "top", // расположение
      },

      // Настройка всплывающих подсказок
      tooltip: {
        mode: "index",     // показывать данные всех линий
        intersect: false,  // срабатывает не только при точном попадании
      },
    },

    // Настройка поведения при наведении
    interaction: {
      mode: "nearest",  // ближайшая точка
      axis: "x",        // ориентироваться по оси X
      intersect: false, // не обязательно точно попадать
    },

    // Настройка осей
    scales: {

      // Ось X (месяцы)
      x: {
        grid: { 
          display: false // убираем вертикальные линии сетки
        },
      },

      // Ось Y (продажи)
      y: {
        beginAtZero: true, // график начинается с 0
        grid: { 
          color: "rgba(0,0,0,0.05)" // цвет горизонтальной сетки
        },
      },
    },
  },
});
